import { describe, expect, it } from "vitest";
import type { Schedule } from "../solver/types";
import { formatAdvisorText } from "./advisorText";

const schedule: Schedule = {
  courses: [
    { course: "CS100", lectureId: "35393", activityIds: ["35406", "32724"], requirementId: "cs-bs-ud-core" },
    { course: "CS005", lectureId: "12992", activityIds: ["33958"], requirementId: "cs-bs-ud-tech-electives" },
  ],
  units: 9,
  score: 0,
};

describe("formatAdvisorText", () => {
  it("lists each course with aligned columns, every component's CRN and times, and the requirement it fills", () => {
    expect(formatAdvisorText(schedule, "Fall 2026", 2)).toBe(
      [
        "Bento schedule — Fall 2026 (Option 2, 9 units)",
        "",
        "CS 100  Software Construction                 5u   LEC 35393 TR 14:00–15:20 | DIS 35406 W 10:00–10:50 | LAB 32724 F 16:00–17:50",
        "  fills: Upper-Division CS Core",
        "CS 005  Introduction To Computer Programming  4u   LEC 12992 MWF 10:00–10:50 | LAB 33958 online",
        "  fills: Technical Electives",
        "",
        "Generated by Bento — verify in R'Web before registering.",
      ].join("\n"),
    );
  });

  it("mentions GE units when the student set some", () => {
    const text = formatAdvisorText(schedule, "Fall 2026", 1, 4);
    expect(text).toContain("Plus 4 GE/other units (not scheduled by Bento) — 13 units total.");
    expect(text.endsWith("Generated by Bento — verify in R'Web before registering.")).toBe(true);
  });
});
