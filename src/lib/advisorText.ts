// Plain-text summary of one option for pasting into an email to an advisor.

import type { Schedule } from "../solver/types";
import { displayCode, titleCase } from "./catalog";
import { courseDetails } from "./scheduleView";
import type { CourseComponent } from "./scheduleView";

function componentText(component: CourseComponent): string {
  if (component.online) return `${component.kind} ${component.crn} online`;
  const times = component.meetings.map((meeting) => `${meeting.days.join("")} ${meeting.start}–${meeting.end}`).join(", ");
  return `${component.kind} ${component.crn} ${times}`;
}

/**
 * Bento schedule — Fall 2026 (Option 2, 16 units)
 *
 * CS 100    Software Construction   5u  LEC 35393 TR 14:00–15:20 | DIS 35406 W 10:00–10:50 | LAB 32724 F 16:00–17:50
 *   fills: Upper-Division CS Core
 * ...
 * Generated by Bento — verify in R'Web before registering.
 */
export function formatAdvisorText(schedule: Schedule, termLabel: string, optionNumber: number, geUnits = 0): string {
  const courses = courseDetails(schedule).map((course) => ({ ...course, code: displayCode(course.code), title: titleCase(course.title) }));
  const codeWidth = Math.max(...courses.map((course) => course.code.length));
  const titleWidth = Math.max(...courses.map((course) => course.title.length));

  const lines = [`Bento schedule — ${termLabel} (Option ${optionNumber}, ${schedule.units} units)`, ""];
  for (const course of courses) {
    lines.push(`${course.code.padEnd(codeWidth)}  ${course.title.padEnd(titleWidth)}  ${`${course.units}u`.padEnd(3)}  ${course.components.map(componentText).join(" | ")}`);
    lines.push(`  fills: ${course.requirement}`);
  }
  lines.push("");
  if (geUnits > 0) lines.push(`Plus ${geUnits} GE/other units (not scheduled by Bento) — ${schedule.units + geUnits} units total.`);
  lines.push("Generated by Bento — verify in R'Web before registering.");
  return lines.join("\n");
}
